#!/usr/bin/env python3
"""`scripts/crate-versions.py` (クレートの版の決まり) の単体テスト (T21.1、T21.6 を経て T26.3 で決まりを置き換えた)。

    python3 -m unittest discover -s scripts        # リポジトリの根から

一時の git リポジトリに本体 (`src/`) とクレート 3 つ (`alpha` `beta` `gamma`) と `proxy-server` を作り、
`main` に 2 つのデプロイ (T1.1 で全部 0.1.1、T2.3 で全部 0.2.3) を積んでから、次の各場合を見る:
そろっている / 中身だけが変わった (NG にせず数える) / `--deploy` でそろえる / 版の行だけの差分 /
1 クレートだけ版がずれた / タグの上 / 形が `X.Y.Z` でない / `--task` の廃止 / 版を下げる `--deploy`。
git の設定は利用者のものを読まない (`GIT_CONFIG_GLOBAL` を空に向ける) ので、署名やフックに左右されない。
"""

import importlib.util
import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.path.join(HERE, "crate-versions.py")


def _load(name, filename):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, filename))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


cv = _load("crate_versions", "crate-versions.py")

ENV = dict(os.environ, GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1",
           GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@example.invalid",
           GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@example.invalid")
CRATES = ["alpha", "beta", "gamma", "server"]


def crate_toml(name, version, comment=False):
    lines = ["[package]", 'name = "%s"' % name]
    if comment:
        lines.append("# 本体と同じ版にそろえる")
    lines += ['version = "%s"' % version, 'edition = "2024"', "", "[dependencies]", ""]
    return "\n".join(lines)


class Repo:
    """一時の git リポジトリ。"""

    def __init__(self, path):
        self.path = path

    def git(self, *args, check=True):
        return subprocess.run(["git", "-C", self.path] + list(args), env=ENV, check=check,
                              stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                              universal_newlines=True).stdout

    def write(self, rel, text):
        full = os.path.join(self.path, rel)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as f:
            f.write(text)

    def read(self, rel):
        with open(os.path.join(self.path, rel), encoding="utf-8") as f:
            return f.read()

    def set_versions(self, version, **overrides):
        """本体と全クレートの版を version にし、overrides (クレートのディレクトリ名) だけ上書きする。"""
        members = "".join('    "crates/%s",\n' % c for c in CRATES)
        self.write("Cargo.toml", "[workspace]\nmembers = [\n%s]\n\n[package]\nname = \"rust-http-proxy\"\n"
                                 "version = \"%s\"\nedition = \"2024\"\n" % (members, version))
        lock = ["# This file is automatically @generated by Cargo.", "version = 4", ""]
        names = {"rust-http-proxy": version}
        for c in CRATES:
            name = "proxy-" + c
            self.write("crates/%s/Cargo.toml" % c, crate_toml(name, overrides.get(c, version), comment=(c == "server")))
            names[name] = overrides.get(c, version)
        for name in sorted(names):
            lock += ["[[package]]", 'name = "%s"' % name, 'version = "%s"' % names[name], ""]
        self.write("Cargo.lock", "\n".join(lock))

    def version(self, c):
        return cv.package_fields(self.read("crates/%s/Cargo.toml" % c))[1]

    def root_version(self):
        return cv.package_fields(self.read("Cargo.toml"))[1]

    def commit(self, msg, tag=None):
        self.git("add", "-A")
        self.git("commit", "-q", "--no-gpg-sign", "-m", msg)
        if tag:
            self.git("tag", tag)

    def run(self, *args):
        out = subprocess.run([sys.executable, TOOL, "-C", self.path] + list(args), env=ENV,
                             stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
        return out.returncode, out.stdout + out.stderr


class CrateVersionsTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="test-crate-versions-")
        self.r = Repo(self.tmp.name)
        self.r.git("init", "-q", "-b", "main")
        # T1.1: 全部を作る (全部 0.1.1)
        self.r.set_versions("0.1.1")
        for c in CRATES:
            self.r.write("crates/%s/src/lib.rs" % c, "// %s\n" % c)
        self.r.write("src/main.rs", "// main\n")
        self.r.commit("T1.1")
        # T2.3: alpha の中身を変えて、デプロイの版を 0.2.3 にそろえる
        self.r.write("crates/alpha/src/lib.rs", "// alpha 2\n")
        self.r.set_versions("0.2.3")
        self.r.commit("T2.3 deploy 0.2.3")

    def tearDown(self):
        self.tmp.cleanup()

    def check(self, code_want):
        code, out = self.r.run("--check")
        self.assertEqual(code, code_want, out)
        return out

    def test_all_equal_passes(self):
        out = self.check(0)
        self.assertIn("決まりに合う: 4 クレート + 本体 (本体 0.2.3)", out)
        self.assertIn("中身が変わったクレート: 0 個", out)
        self.assertNotIn("--deploy", out)
        code, out = self.r.run("--list")
        self.assertEqual(code, 0, out)
        self.assertIn("合わない: 0", out)

    def test_content_change_is_counted_not_ng(self):
        # デプロイ前は中身が変わっているのが普通。NG にせず、数えて次のデプロイを案内する
        self.r.write("crates/gamma/src/lib.rs", "// gamma 2\n")
        out = self.check(0)
        self.assertIn("前回のデプロイ (", out)
        self.assertIn("から中身が変わったクレート: 1 個", out)
        self.assertIn("次のデプロイで --deploy X.Y.Z する", out)
        self.assertNotIn("NG", out)
        # 本体 (src/) も同じ 1 行で言う
        self.r.write("src/main.rs", "// main 2\n")
        out = self.check(0)
        self.assertIn("から中身が変わったクレート: 1 個 (本体 src/ も変わった)", out)

    def test_deploy_sets_every_unit(self):
        self.r.write("crates/gamma/src/lib.rs", "// gamma 2\n")
        lock_before = self.r.read("Cargo.lock")
        code, out = self.r.run("--deploy", "0.3.0")
        self.assertEqual(code, 0, out)
        self.assertIn("そろえた: 5 (全クレート + 本体 + proxy-server を 0.3.0 に)", out)
        self.assertEqual(self.r.root_version(), "0.3.0")
        for c in CRATES:
            self.assertEqual(self.r.version(c), "0.3.0")
        # Cargo.lock は 5 行 (本体 + 4 クレート) の版だけが変わる
        before, after = lock_before.splitlines(), self.r.read("Cargo.lock").splitlines()
        self.assertEqual(len(before), len(after))
        self.assertEqual([b for a, b in zip(before, after) if a != b], ['version = "0.3.0"'] * 5)
        # コミット前 (作業ツリー) でも決まりに合う。中身の変化はまだ「前回のデプロイから」に数えられる
        out = self.check(0)
        self.assertIn("から中身が変わったクレート: 1 個", out)
        self.r.commit("deploy 0.3.0")
        out = self.check(0)
        self.assertIn("決まりに合う: 4 クレート + 本体 (本体 0.3.0)", out)
        self.assertIn("中身が変わったクレート: 0 個", out)
        # もう一度回しても何も変わらない
        code, out = self.r.run("--deploy", "0.3.0")
        self.assertEqual(code, 0, out)
        self.assertIn("そろえた: 0", out)

    def test_deploy_fixes_one_drifted_crate(self):
        # わざと 1 クレートだけ版を変えると NG。--deploy で同じ版に戻すと通る
        self.r.set_versions("0.2.3", gamma="0.2.2")
        self.r.commit("gamma だけずらした")
        out = self.check(1)
        self.assertIn("NG proxy-gamma: 版 0.2.2 が本体 rust-http-proxy 0.2.3 と違う", out)
        code, out = self.r.run("--deploy", "0.2.3")
        self.assertEqual(code, 0, out)
        self.assertIn("そろえた: 1", out)
        self.assertEqual(self.r.version("gamma"), "0.2.3")
        self.check(0)

    def test_server_must_follow_root(self):
        self.r.set_versions("0.2.3", server="0.2.2")
        self.r.commit("server drifts")
        out = self.check(1)
        self.assertIn("NG proxy-server: 版 0.2.2 が本体 rust-http-proxy 0.2.3 と違う", out)

    def test_deploy_refuses_lower_and_bad_form(self):
        code, out = self.r.run("--deploy", "0.2.2")
        self.assertEqual(code, 2, out)
        self.assertIn("版は下げない", out)
        code, out = self.r.run("--deploy", "0.3")
        self.assertEqual(code, 2, out)
        self.assertIn("X.Y.Z の形で渡す", out)
        self.assertEqual(self.r.root_version(), "0.2.3")  # 何も書かない

    def test_version_line_only_is_not_content(self):
        # 版の行だけを上げても「中身が変わった」に数えない (デプロイの直前の 1 回がこれ)
        self.r.set_versions("0.2.4")
        out = self.check(0)
        self.assertIn("中身が変わったクレート: 0 個", out)
        # 版の行の外の Cargo.toml の変更は中身に数える
        self.r.write("crates/beta/Cargo.toml", self.r.read("crates/beta/Cargo.toml") + "# メモ\n")
        out = self.check(0)
        self.assertIn("から中身が変わったクレート: 1 個", out)

    def test_untracked_file_counts(self):
        self.r.write("crates/beta/src/new.rs", "// new\n")
        out = self.check(0)
        self.assertIn("から中身が変わったクレート: 1 個", out)

    def test_tag(self):
        self.r.git("tag", "v0.2.3")
        self.check(0)
        self.r.git("tag", "v0.2.4")
        self.r.git("tag", "-d", "v0.2.3")
        out = self.check(1)
        self.assertIn("タグ v0.2.4", out)
        self.assertIn("の上なのに本体の版が 0.2.3 (決まり b)", out)
        # タグの上でなければ見ない
        self.r.write("README.md", "docs\n")
        self.r.commit("docs")
        self.check(0)

    def test_form(self):
        self.r.set_versions("1.0")
        self.r.commit("形が違う")
        out = self.check(1)
        self.assertIn("NG rust-http-proxy: 版 1.0 が X.Y.Z の形でない (決まり a)", out)

    def test_task_is_gone(self):
        code, out = self.r.run("--task", "T2.5")
        self.assertEqual(code, 2, out)
        self.assertIn("--task は廃止した (T26.3)", out)
        self.assertIn("--deploy 0.26.0", out)
        # --since も受けない (使い方の誤り = 2)
        code, out = self.r.run("--check", "--since", "HEAD")
        self.assertEqual(code, 2, out)

    def test_merge_counts_both_sides(self):
        # 2 つの枝がそれぞれ別のクレートを変えてマージされたら、2 個と数える (NG にはしない)
        self.r.git("checkout", "-q", "-b", "t31")
        self.r.write("crates/gamma/src/a.rs", "// a\n")
        self.r.commit("gamma")
        self.r.git("checkout", "-q", "-b", "t32", "main")
        self.r.write("crates/beta/src/b.rs", "// b\n")
        self.r.commit("beta")
        self.r.git("checkout", "-q", "main")
        self.r.git("merge", "-q", "--no-edit", "--no-gpg-sign", "t31")
        out = self.check(0)
        self.assertIn("から中身が変わったクレート: 1 個", out)
        self.r.git("merge", "-q", "--no-edit", "--no-gpg-sign", "t32")
        out = self.check(0)
        self.assertIn("から中身が変わったクレート: 2 個", out)
        # そろえてコミットすれば 0 に戻る
        self.r.run("--deploy", "0.3.0")
        self.r.commit("deploy 0.3.0")
        out = self.check(0)
        self.assertIn("中身が変わったクレート: 0 個", out)

    def test_deploy_after_merge_conflict_resolution(self):
        # 2 つの枝が同じクレートに触れたマージでも、デプロイは全クレートを同じ版にする
        self.r.git("checkout", "-q", "-b", "t31")
        self.r.write("crates/gamma/src/a.rs", "// a\n")
        self.r.commit("gamma a")
        self.r.git("checkout", "-q", "-b", "t32", "main")
        self.r.write("crates/gamma/src/b.rs", "// b\n")
        self.r.commit("gamma b")
        self.r.git("checkout", "-q", "main")
        self.r.git("merge", "-q", "--no-edit", "--no-gpg-sign", "t31")
        self.r.git("merge", "-q", "--no-edit", "--no-gpg-sign", "t32")
        self.check(0)
        code, out = self.r.run("--deploy", "0.4.0")
        self.assertEqual(code, 0, out)
        self.r.commit("deploy 0.4.0")
        self.check(0)

    def test_a_lowered_version_is_ng(self):
        # 決まり (c): 版は下げない。履歴で一度使った 0.2.3 より低い版を書いたら NG
        self.r.write("crates/gamma/Cargo.toml", crate_toml("gamma", "0.2.2"))
        out = self.check(1)
        self.assertIn("NG gamma: 版 0.2.2 が履歴で一度使った 0.2.3 より低い (決まり c。版は下げない)", out)
        # 元に戻せば通る (下げたままだけが NG)
        self.r.write("crates/gamma/Cargo.toml", crate_toml("gamma", "0.2.3"))
        self.check(0)

    def test_history_is_skipped_when_shallow(self):
        # 浅い履歴では数えられないので、決まり (c) は判定しない (取りこぼしても誤 NG にしない)
        shallow = self.tmp.name + "-shallow"
        subprocess.run(["git", "clone", "-q", "--depth", "1", "file://" + self.tmp.name, shallow],
                       env=ENV, check=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        repo = cv.Repo(shallow)
        try:
            self.assertEqual(repo.high_water_marks(), {})
        finally:
            repo.close()

    def test_without_version_line(self):
        a = crate_toml("x", "0.1.0", comment=True)
        b = crate_toml("x", "0.2.0", comment=True)
        self.assertNotEqual(a, b)
        self.assertEqual(cv.without_version_line(a), cv.without_version_line(b))
        # [dependencies] の中の version は版の行ではない
        c = "[package]\nname = \"x\"\nversion = \"1.0.0\"\n[dependencies]\nversion = \"2\"\n"
        self.assertEqual(cv.without_version_line(c), "[package]\nname = \"x\"\n[dependencies]\nversion = \"2\"\n")

    def test_ver_key(self):
        self.assertEqual(cv.ver_key("0.26.0"), (0, 26, 0))
        self.assertEqual(cv.ver_key("1.2.3"), (1, 2, 3))
        self.assertIsNone(cv.ver_key("0.26"))
        self.assertIsNone(cv.ver_key("v0.26.0"))


if __name__ == "__main__":
    unittest.main()
